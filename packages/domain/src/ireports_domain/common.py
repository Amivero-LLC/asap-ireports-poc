# Prefixed, opaque identifiers.
#
# Prefixes are not decoration. `run_id` and `finding_id` are passed adjacently through
# orchestration, delivery, and audit records, and a transposition between them is invisible at a
# type level if both are bare strings. The prefix makes that mistake a validation error.
#
# Written out one per line rather than generated by a helper: a factory returning `Annotated[...]`
# is a *value* to a type checker, not a type alias, so every field annotated with one silently
# degrades to `Any` under mypy. Verbosity here buys real static checking.

