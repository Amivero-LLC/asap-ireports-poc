class DecisionDomain(StrEnum):
    """The distinct legal authorities this system analyses against.

    ADR-003 and blueprint §2.1: suitability, fitness, PIV credentialing, and national-security
    eligibility are distinct authorities with distinct criteria. Collapsing them produces
    analysis that is wrong in a way that is hard to detect, so every finding names exactly one.
    """

    SUITABILITY = "suitability"
    FITNESS = "fitness"
    NATIONAL_SECURITY_ELIGIBILITY = "national_security_eligibility"
    PIV_CREDENTIALING = "piv_credentialing"


