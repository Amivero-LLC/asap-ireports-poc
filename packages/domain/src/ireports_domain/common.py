# ---------------------------------------------------------------------------
# Decision-support boundary (CLAUDE.md, blueprint §10.4)
# ---------------------------------------------------------------------------

_DETERMINATIVE_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(r"\b(is|are|was|were)\s+(not\s+)?(suitable|unsuitable|fit|unfit)\b", re.I),
        "states a suitability or fitness determination",
    ),
    (
        re.compile(r"\b(is|are)\s+(not\s+)?(eligible|ineligible)\b", re.I),
        "states an eligibility determination",
    ),
    (
        # Verb forms: "should be denied", "recommend that eligibility be revoked".
        # The bridge stops at clause boundaries so that an unrelated later clause
        # ("...should be reviewed; access was granted in 2019") is not swept in.
        re.compile(
            r"\b(should|must|shall|recommend(?:s|ed)?)\b[^.;]{0,30}?\b"
            r"(denied|revoked|granted|suspended|debarred|disqualif\w*)\b",
            re.I,
        ),
        "recommends a final adjudicative action",
    ),
    (
        # Noun forms: "recommend denial", "advises revocation of the clearance".
        re.compile(
            r"\b(recommend(?:s|ed|ation|ations)?|advise[sd]?|propose[sd]?)\b[^.;]{0,30}?\b"
            r"(denial|revocation|suspension|debarment|disqualification)\b",
            re.I,
        ),
        "recommends a final adjudicative action",
    ),
    (
        re.compile(
            r"\bclearance\s+(should|must|shall|will)\s+be\b|\b(deny|revoke|grant|suspend)\s+"
            r"(the\s+)?(clearance|eligibility|access)\b",
            re.I,
        ),
        "directs a clearance action",
    ),
    (
        re.compile(r"\bviolated\s+(SEAD|5\s*CFR|the\s+(guideline|standard|policy))", re.I),
        "asserts a legal violation as fact",
    ),
    (
        re.compile(
            r"\b(subject|applicant|individual)\s+(is|was)\s+(deceptive|dishonest|lying)\b", re.I
        ),
        "asserts a credibility conclusion reserved to the officer",
    ),
    (
        re.compile(
            r"\b(will|is\s+likely\s+to)\s+(reoffend|commit|engage\s+in\s+misconduct)\b", re.I
        ),
        "predicts future misconduct",
    ),
)


def reject_determinative_language(value: str) -> str:
    """Reject narrative text that crosses the decision-support boundary.

    The system identifies evidence-backed issues for review by an authorized officer. It must
    never grant, deny, revoke, suspend, or otherwise make a final determination. That boundary
    is enforced here, deterministically, on every narrative field a model can write into.

    This is a guard, not a proof. It catches the specific formulations blueprint §10.4 lists as
    prohibited, and it cannot catch every possible phrasing.

    **It used to have a backstop and no longer does.** An earlier version of this docstring called
    it "not a substitute for the human review gate (ADR-011)" — but ADR-022 removed that gate
    entirely, because review happens in ASAP rather than inside a run. The boundary now rests on
    two mechanisms, not three: this guard, and the fact that `ProposedFinding` is the only finding
    type there is. Weakening either one is not a defence-in-depth trade; it is the boundary.
    """
    for pattern, why in _DETERMINATIVE_PATTERNS:
        match = pattern.search(value)
        if match:
            raise ValueError(
                f"text crosses the decision-support boundary: it {why} "
                f"(matched {match.group(0)!r}). Findings describe what the record indicates and "
                f"what requires officer review; they do not state determinations."
            )
    return value


DecisionSupportText = Annotated[
    str,
    StringConstraints(min_length=1, strip_whitespace=True),
    AfterValidator(reject_determinative_language),
]
"""Narrative text a model may write. Guarded against determinative language."""


