"""Shared primitives for every contract in this package.

Three things live here that the rest of the package depends on:

1. `ContractModel` — the base class that makes every contract strict at the boundary.
2. Identifier and scalar types, so an evidence id cannot be passed where a finding id belongs.
3. `DecisionSupportText` — the deterministic language guard that enforces the decision-support
   boundary in `CLAUDE.md`. It is ordinary code, not a prompt instruction, because a model must
   not be the thing that decides whether its own output stayed inside the boundary.
"""

from __future__ import annotations

import re
from datetime import datetime
from enum import StrEnum
from typing import Annotated, Literal, get_args

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, StringConstraints

# ---------------------------------------------------------------------------
# Contract versioning
# ---------------------------------------------------------------------------

ContractVersion = Literal["2.0.0"]
"""The contract set's version, as a type.

Every contract declares `schema_version: ContractVersion`, so a payload written against an
unknown version fails validation loudly instead of being partially understood. Blueprint §10.1:
breaking changes require a new major version and a compatibility plan.

Spelled as a `Literal` of a string constant rather than `Literal[CONTRACT_VERSION]` because the
latter is not a valid type to a type checker — `Literal` needs a literal. `CONTRACT_VERSION`
below is the runtime value, and `_assert_version_agreement` keeps the two from drifting.
"""

CONTRACT_VERSION: ContractVersion = "2.0.0"
"""Runtime value of `ContractVersion`, for use as a field default and in generated schemas."""


def _assert_version_agreement() -> None:
    """Fail at import if the type and the value disagree.

    Bumping one and forgetting the other would produce contracts that validate against a version
    they do not declare — precisely the silent mismatch the version pin exists to prevent.
    """
    permitted = get_args(ContractVersion)
    if CONTRACT_VERSION not in permitted:
        raise RuntimeError(
            f"CONTRACT_VERSION {CONTRACT_VERSION!r} is not a member of ContractVersion {permitted}"
        )


_assert_version_agreement()


# ---------------------------------------------------------------------------
# Base model
# ---------------------------------------------------------------------------


class ContractModel(BaseModel):
    """Base for every contract.

    `extra="forbid"` is the load-bearing setting. These models sit at boundaries between
    ingestion, orchestration, human review, and ASAP delivery, and a silently-dropped unknown
    field at a boundary is how a contract mismatch becomes a data-loss bug. Forbidding extras
    turns that into a validation error at the seam where it happened.

    `frozen=True` supports ADR-011: the machine proposal must remain immutable once a human
    disposition references it. Constructing a variant is `model_copy(update=...)`, which is
    explicit and reviewable, rather than in-place mutation.
    """

    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
        str_strip_whitespace=True,
        validate_default=True,
        use_enum_values=False,
    )


